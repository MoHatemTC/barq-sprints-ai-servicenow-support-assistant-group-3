"""Run every mock scenario against the LIVE endpoint and write docs/sample_runs.md.

Usage:
    cp .env.example .env   # fill in LLM_API_KEY / LLM_MODEL / LLM_BASE_URL
    python scripts/run_samples.py

The output file contains REAL model output only - nothing is hand-written. The API key is
never written. Re-run whenever the prompt changes and commit the refreshed file.
"""

from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from support_agent.agent import generate_recommendation  # noqa: E402
from support_agent.config import Settings  # noqa: E402
from support_agent.formatting import format_incident_block, format_knowledge_block  # noqa: E402
from support_agent.mock_data import SCENARIOS  # noqa: E402
from support_agent.models import normalize_chunks  # noqa: E402

OUT = ROOT / "docs" / "sample_runs.md"


def main() -> None:
    settings = Settings.from_env()  # fails fast with a clear message if env is missing
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    md = [
        "# Sample Runs (live LLM endpoint)",
        "",
        f"- Generated: {stamp}",
        f"- Model: `{settings.model}`  |  temperature: `{settings.temperature}`",
        "- Generated by `python scripts/run_samples.py`; output below is verbatim, not edited.",
        "- `Model raw output` is what the LLM returned. `Final result` is what the caller receives "
        "after deterministic validation (`support_agent/validation.py`).",
        "",
    ]
    for name, sc in SCENARIOS.items():
        print(f"running {name} ...")
        result = generate_recommendation(
            sc["incident"],
            sc["chunks"],
            settings=settings,
            short_circuit_on_empty=sc.get("short_circuit_on_empty", True),
        )
        chunks = normalize_chunks(sc["chunks"])
        md += [
            f"## {name}: {sc['title']}",
            "",
            f"**Status:** `{result.status}`  |  **LLM called:** `{result.llm_called}`  |  "
            f"**Decline reason:** `{result.decline_reason}`  |  **Cited:** `{result.cited_articles}`",
            "",
            "**Prompt input (knowledge block first, then untrusted incident block):**",
            "",
            "```text",
            format_knowledge_block(chunks),
            "",
            format_incident_block(sc["incident"]),
            "```",
            "",
        ]
        if result.tool_calls:
            md += ["**Tool calls made:** " + ", ".join(f"`{c['tool']}`" for c in result.tool_calls), ""]
        if result.warnings:
            md += ["**Warnings:** " + "; ".join(result.warnings), ""]
        md += [
            "**Model raw output:**",
            "",
            "```text",
            result.raw_output if result.raw_output is not None else "(LLM not called)",
            "```",
            "",
            "**Final result returned by `generate_recommendation`:**",
            "",
            "```text",
            result.text,
            "```",
            "",
        ]
    OUT.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
